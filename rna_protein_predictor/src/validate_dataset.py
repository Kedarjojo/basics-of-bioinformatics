"""Generate machine-readable and human-readable dataset diagnostics."""

from __future__ import annotations

import json

import pandas as pd

from .config import REPORTS_DIR, TABLES_DIR
from .data_prep import KEY, load_model_table


def _markdown_table(frame: pd.DataFrame) -> str:
    """Render a compact Markdown table without optional pandas dependencies."""
    display = frame.copy()
    for column in display.select_dtypes(include="number"):
        display[column] = display[column].map(
            lambda value: f"{value:.4f}" if isinstance(value, float) else str(value)
        )
    header = "| " + " | ".join(display.columns) + " |"
    divider = "| " + " | ".join("---" for _ in display.columns) + " |"
    rows = ["| " + " | ".join(map(str, row)) + " |" for row in display.to_numpy()]
    return "\n".join([header, divider, *rows])


def main() -> None:
    clean, duplicates = load_model_table()
    loc_cols = [c for c in clean if c.startswith("loc_")]
    required = [
        *KEY,
        "protein_detected",
        "tumor_log2tpm_mean",
        "rna_log2fc",
        "gene_length",
    ]

    summary = {
        "clean_rows": int(len(clean)),
        "genes": int(clean["ensembl_base"].nunique()),
        "cancers": sorted(clean["cancer"].unique().tolist()),
        "duplicate_source_rows": int(len(duplicates)),
        "duplicate_keys": int(duplicates.groupby(KEY).ngroups),
        "localization_features": len(loc_cols),
        "missing_fraction": {
            c: float(clean[c].isna().mean()) for c in required if c in clean
        },
        "target_counts": {
            str(k): int(v)
            for k, v in clean["protein_detected"].value_counts().items()
        },
    }

    coverage = (
        clean.groupby("localization_available")["protein_detected"]
        .agg(rows="size", detection_rate="mean")
        .reset_index()
    )
    by_cancer = (
        clean.groupby("cancer")
        .agg(
            rows=("ensembl_base", "size"),
            genes=("ensembl_base", "nunique"),
            detection_rate=("protein_detected", "mean"),
            localization_coverage=("localization_available", "mean"),
            median_hpa_patients=("total_patients", "median"),
        )
        .reset_index()
    )

    duplicates.to_csv(TABLES_DIR / "duplicate_gene_cancer_rows.csv", index=False)
    coverage.to_csv(TABLES_DIR / "localization_coverage_audit.csv", index=False)
    by_cancer.to_csv(TABLES_DIR / "dataset_summary_by_cancer.csv", index=False)
    with (REPORTS_DIR / "dataset_audit.json").open("w", encoding="utf-8") as handle:
        json.dump(summary, handle, indent=2)

    lines = [
        "# Dataset audit",
        "",
        f"- Clean provisional rows: {summary['clean_rows']:,}",
        f"- Unique genes: {summary['genes']:,}",
        f"- Duplicate source rows: {summary['duplicate_source_rows']:,}",
        f"- Duplicate gene-cancer keys: {summary['duplicate_keys']:,}",
        f"- Localization features: {summary['localization_features']}",
        "",
        "## Localization coverage and IHC detection",
        "",
        _markdown_table(coverage),
        "",
        "## Cancer-level summary",
        "",
        _markdown_table(by_cancer),
        "",
        "Generated by `python -m src.validate_dataset`.",
    ]
    (REPORTS_DIR / "dataset_audit.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
